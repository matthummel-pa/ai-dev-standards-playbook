#!/usr/bin/env bash
# Shared helpers for new-theme.sh and wp-local.sh. Source it; do not run it.

die() { echo "error: $*" >&2; exit 1; }
say() { echo "• $*"; }
have() { command -v "$1" >/dev/null 2>&1; }
is_windows() { case "$(uname -s)" in MINGW* | MSYS* | CYGWIN*) return 0 ;; *) return 1 ;; esac; }
winpath() { if is_windows; then cygpath -w "$1"; else printf '%s' "$1"; fi; }

# Escape a value for use as a sed replacement: backslash, &, and both delimiters we use (| and #).
sed_escape() { printf '%s' "$1" | sed -e 's/[\\&|#]/\\&/g'; }

# Extensions Composer and Acorn need.
PHP_NEEDED_EXTS="openssl mbstring curl zip fileinfo"

# Print (space-separated) the needed extensions the current php does not load.
php_missing_exts() {
  local mods m out=""
  mods="$(php -m | tr -d '\r' | tr '[:upper:]' '[:lower:]')"
  for m in $PHP_NEEDED_EXTS; do
    grep -qx "$m" <<<"$mods" || out="$out $m"
  done
  printf '%s' "$out"
}

# PHP 8.3+ with the extensions above. Some installs (scoop on Windows) ship without them.
# When any are missing, write a private php.ini and point PHPRC at it. PHPRC replaces the primary
# php.ini, so the private file starts from a copy of it and only then adds what is missing.
# The global PHP config is never edited.
ensure_php() {
  have php || die "php not found. Windows: scoop install versions/php83 · macOS: brew install php@8.3"
  local ver
  ver="$(php -r 'echo PHP_MAJOR_VERSION*100+PHP_MINOR_VERSION;' | tr -d '\r')"
  [ "$ver" -ge 803 ] || die "PHP 8.3+ required (found $(php -r 'echo PHP_VERSION;' | tr -d '\r'))"

  local miss m
  miss="$(php_missing_exts)"
  [ -z "$miss" ] && return 0
  is_windows || die "PHP is missing extensions:$miss. Install them with your package manager."

  local dir="${XDG_CACHE_HOME:-$HOME/.cache}/playbook-php" bin ext loaded
  mkdir -p "$dir"
  bin="$(php -r 'echo PHP_BINARY;' | tr -d '\r' | sed 's|\\|/|g')"
  ext="$(dirname "$bin")/ext"
  [ -d "$ext" ] || ext="$(php -r 'echo ini_get("extension_dir");' | tr -d '\r' | sed 's|\\|/|g')"
  loaded="$(php -r 'echo php_ini_loaded_file();' | tr -d '\r' | sed 's|\\|/|g')"
  {
    echo "; Generated by ai-dev-standards-playbook/scripts/lib-wp.sh. Safe to delete."
    if [ -n "$loaded" ] && [ -f "$loaded" ]; then
      echo "; --- copy of $loaded (PHPRC would otherwise replace it) ---"
      tr -d '\r' <"$loaded"
      echo
    fi
    echo "; --- added by the playbook ---"
    echo "memory_limit = 512M"
    echo "date.timezone = UTC"
    echo "extension_dir = \"$ext\""
    for m in $miss; do echo "extension = $m"; done
  } >"$dir/php.ini"
  PHPRC="$(winpath "$dir")"
  export PHPRC

  miss="$(php_missing_exts)"
  [ -z "$miss" ] || die "PHP still lacks:$miss with $dir/php.ini. Check that the extension DLLs exist in $ext."
  say "PHP lacked some extensions. Using a private php.ini in $dir (global config untouched)."
}

# COMPOSER_BIN overrides, e.g. COMPOSER_BIN="php /path/composer.phar".
composer_run() {
  if [ -n "${COMPOSER_BIN:-}" ]; then
    # shellcheck disable=SC2086
    $COMPOSER_BIN "$@"
  elif have composer; then
    composer "$@"
  else
    die "composer not found. Windows: scoop install composer · macOS: brew install composer · or set COMPOSER_BIN"
  fi
}

# Sage 11 needs Node ^20.19.0 || >=22.12.0 (its package.json "engines").
ensure_node() {
  have node || die "node not found. Install Node 22 LTS (Sage 11 needs ^20.19 or >=22.12)."
  node -e 'const [a, b] = process.versions.node.split(".").map(Number); process.exit((a === 20 && b >= 19) || (a === 22 && b >= 12) || a > 22 ? 0 : 1)' \
    || die "Node ^20.19 or >=22.12 required (found $(node -v | tr -d '\r'))"
}

# Theme folder name WordPress will use: read from the Vite base, else the directory name.
theme_folder() { # $1 = repo dir
  local base
  base="$(sed -n "s|.*base:[[:space:]]*['\"]/wp-content/themes/\([^/]*\)/.*|\1|p" "$1/vite.config.js" 2>/dev/null | head -1)"
  if [ -n "$base" ]; then printf '%s' "$base"; else basename "$1"; fi
}

# Install what a fresh clone lacks, then build once so the theme does not fatal on a missing manifest.
prepare_theme() { # $1 = repo dir
  ensure_php
  ensure_node
  (
    cd "$1" || exit 1
    if [ ! -f vendor/autoload.php ]; then say "composer install"; composer_run install --no-interaction --prefer-dist --no-progress; fi
    # npm writes node_modules/.package-lock.json last, so a bare node_modules folder is an interrupted install.
    if [ ! -f node_modules/.package-lock.json ]; then
      say "npm install"
      if [ -f package-lock.json ]; then npm ci --no-audit --no-fund; else npm install --no-audit --no-fund; fi
    fi
    if [ ! -f public/build/manifest.json ]; then say "npm run build"; npm run build; fi
  )
}
